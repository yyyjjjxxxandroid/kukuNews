package com.ixuea.superui.util

import java.util.regex.Pattern

/**
 * 正则表达式相关方法
 */
object SuperRegularUtil {


    /**
     * 是否是手机号
     *
     * @param data
     * @return
     */
    //在函数内部，通过 Pattern.compile(REGEX_PHONE).matcher(data).matches() 语句来进行验证。
    //首先，Pattern.compile(REGEX_PHONE) 会根据预先定义好的手机号码正则表达式 REGEX_PHONE 来创建一个 Pattern 对象，
    // 这个正则表达式涵盖了中国移动、联通、电信以及虚拟运营商的常见手机号码号段格式。
    //然后，使用创建好的 Pattern 对象的 matcher 方法，传入要验证的字符串 data，得到一个 Matcher 对象，这个对象可以用于对字符串进行匹配操作。
    //最后，调用 Matcher 对象的 matches 方法，该方法会尝试将整个输入字符串 data 与正则表达式进行匹配，
    // 如果完全匹配成功，则返回 true，表示输入的字符串是一个合法的手机号码；否则返回 false。
    fun isPhone(data: String): Boolean {
        return Pattern.compile(REGEX_PHONE).matcher(data).matches()
    }

    /**
     * 是否是邮箱
     *
     * @param data
     * @return
     */
    fun isEmail(data: String): Boolean {
        return Pattern.compile(REGEX_EMAIL).matcher(data).matches()
    }

    /**
     * 手机号正则表达式
     * 移动：134 135 136 137 138 139 147 150 151 152 157 158 159 178 182 183 184 187 188 198
     * 联通：130 131 132 145 155 156 166 171 175 176 185 186
     * 电信：133 149 153 173 177 180 181 189 199
     * 虚拟运营商: 170
     */
    const val REGEX_PHONE = "^(13[0-9]|14[579]|15[0-3,5-9]|16[6]|17[0135678]|18[0-9]|19[89])\\d{8}$"

    /**
     * 邮箱正则表达式
     */
    const val REGEX_EMAIL = "^([a-z0-9_\\.-]+)@([\\da-z\\.-]+)\\.([a-z\\.]{2,6})$"
    //正则表达式解析
    //手机号码正则表达式（REGEX_PHONE）：
    //^(13[0-9]|14[579]|15[0-3,5-9]|16[6]|17[0135678]|18[0-9]|19[89])\\d{8}$ 这个正则表达式的具体含义如下：
    //^ 表示匹配字符串的开始位置，确保从字符串开头进行匹配。
    //(13[0-9]|14[579]|15[0-3,5-9]|16[6]|17[0135678]|18[0-9]|19[89]) 这部分是一个分组，使用 | 来分隔不同的选择项，
    // 列举了各个运营商的手机号码号段前缀。例如 13[0-9] 表示以 13 开头，后面跟着任意一位 0 - 9 的数字，涵盖了像 134、135 等号段；同理其他部分分别对应不同运营商的相关号段情况。
    //\\d{8} 表示后面紧接着要匹配 8 位数字，确保手机号码整体长度符合要求（前面号段部分占 3 位，加上后面 8 位数字，总共 11 位）。
    //$ 表示匹配字符串的结束位置，保证整个字符串刚好完整匹配正则表达式所定义的手机号码格式，不存在多余的字符。
    //邮箱正则表达式（REGEX_EMAIL）：
    //^([a-z0-9_\\.-]+)@([\\da-z\\.-]+)\\.([a-z\\.]{2,6})$ 的含义如下：
    //^ 同样是匹配字符串开始位置。
    //([a-z0-9_\\.-]+) 是第一个分组，用于匹配邮箱地址中 @ 符号之前的部分，允许包含小写字母、数字、下划线、点号和短横线，并且至少出现一次（+ 表示前面的字符组合出现一次或多次）。
    //@ 就是邮箱地址中必不可少的 @ 符号。
    //([\\da-z\\.-]+) 为第二个分组，匹配 @ 符号之后、域名 . 之前的部分，同样允许出现数字、小写字母、点号和短横线，且至少出现一次。
    //\\. 表示域名中的点号（在正则表达式中，点号本身有特殊含义，需要使用 \\ 进行转义来表示真正的点号）。
    //([a-z\\.]{2,6}) 是第三个分组，用于匹配域名的后缀部分，要求由小写字母和点号组成，长度在 2 到 6 个字符之间，例如 .com、.net、.org 等常见域名后缀格式都能涵盖在内。
    //$ 匹配字符串的结束位置，确保整个字符串完整符合邮箱地址的格式定义。
}